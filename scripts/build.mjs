/** Deterministic, dependency-free browser bundle. Never contacts Home Assistant. */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const engine = (await readFile(new URL('src/guidance.js', root), 'utf8'))
  .replace(/^export\s+(?=(?:const|let|function|class)\b)/gm, '')
  .replace(/^export\s*\{[^}]*\};?\s*$/gm, '');
const card = (await readFile(new URL('src/air-quality-guidance-card.js', root), 'utf8'))
  .replace(/^import\s+\{[^}]*\}\s+from\s+["']\.\/guidance\.js["'];\s*/m, '');
const output = `/* Generated by scripts/build.mjs. MIT: see LICENSE. */\n${engine}\n${card}`;
const target = new URL('dist/air-quality-guidance-card.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw Error('Bundle is stale: run npm run build');
  console.log('Bundle matches source');
} else {
  await writeFile(target, output);
  console.log(`Built ${fileURLToPath(target)}`);
}
